require_once __DIR__ . '/constants.php';

// THEME_FOLDER points to the asset sources in resources/assets/. Subdirectories there (core/,
// invoiceplane/, invoiceplane_blue/, …) are the available themes as listed by Settings; each
// theme is described by its <theme>.theme file. The browser-facing files are generated by
// "yarn build" (Grunt) into public/assets/, which is not tracked, so the theme list must read
// the tracked sources: pointing it at a missing or unbuilt directory makes
// Mdl_Settings::get_themes()'s directory_map() return nothing, the theme dropdown empty and any
// system_theme allowlist built from it reject every value. Do not change this to views/themes/.
defined('THEME_FOLDER') || define('THEME_FOLDER', $base . '/resources/assets/');

defined('SUMEX_SETTINGS') || define('SUMEX_SETTINGS', env_bool('SUMEX_SETTINGS', false));

